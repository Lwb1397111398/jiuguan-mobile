def render(key: str, store: ProjectStore, **params) -> str:
    """渲染任务模板：用户覆盖优先（task_template_<key>），未覆盖用内置默认。

    {占位符} 逐个替换（不做 str.format，模板中的 JSON 花括号不受影响）；
    中文别名（{章名} 等）映射到对应英文参数，供自定义模板使用。
    """
    template = store.get_task_template(key) or TEMPLATES.get(key, "")
    if key in ("outline_single", "outline_chapter") and "chapter_title" not in params:
        params = {**params, "chapter_title": "未命名"}
    # 自定义 volume 模板漏写 {chapter_rule} 占位符时兜底追加（否则「手动指定本卷章数」
    # 的硬性要求被整体丢弃，AI 照旧自动决定章数——2026-08-27 用户真实踩坑）
    if (key == "volume" and "{chapter_rule}" not in template
            and params.get("chapter_rule")):
        rule = str(params["chapter_rule"])
        template = template.rstrip() + f"\n\n【本卷章数要求】{rule}"
    for alias, eng in _PLACEHOLDER_ALIASES.items():
        if "{" + alias + "}" in template and eng in params:
            template = template.replace("{" + alias + "}", str(params[eng]))
    for k, v in params.items():
        template = template.replace("{" + k + "}", str(v))
    return template
