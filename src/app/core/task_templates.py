# ---------- 单方案化（2026-11-11 老板拍板「所有多方案默认改 1 个」）----------
# 依据：同一任务出多份候选时，模型把力气摊薄，单版反而更完整；不满意直接重新
# 生成更省时省 token。桌面（分卷迭代 / 总纲迭代）与手机版共用本函数，别各写一份。
# 角色系统提示词里仍写着「每个候选」「候选之间要有区别」（保留多方案能力，不迁移
# 老库角色提示词），所以必须在任务指令末尾补「以本段为准」的强约束压住它。
MULTI_PLAN_PHRASES = (
    "（多方案时：方案二/方案三同理，方案之间空一行分隔。）",
    "（方案二/方案三同理），",
    "（方案二/方案三同理）",
    "候选之间空一行分隔。",
    "方案之间空一行分隔。",
    "候选之间落实意见的方式要有明显区别。",
    "候选方案之间对修改意见的落实方式要有明显区别。",
)

_SINGLE_PLAN_RULE = (
    "\n\n【本次输出要求·以本段为准】本次只输出 1 个{noun}："
    "以一级标题『{heading}』开头，{detail}写完即结束；"
    "不要输出方案二、方案三，不要写候选对比、评估或任何说明文字。"
    "即使系统提示词或其它段落提到「多个候选」「候选之间要有区别」，本次也以这里为准。"
)


def single_plan_task(text: str, *, heading: str, noun: str = "方案",
                     detail: str = "") -> str:
    """把多方案任务指令改写成单方案：摘掉多候选措辞 + 末尾追加强约束。

    heading：单方案标题行（如「# 方案一：方案标题」）；
    noun：方案的说法（分卷迭代用「修订方案」）；
    detail：标题行之后的动作说明（可空，如「标题下直接写修订后的本卷描述，」）。
    """
    for phrase in MULTI_PLAN_PHRASES:
        text = text.replace(phrase, "")
    if detail and not detail.endswith(("，", "；", "。")):
        detail = detail.rstrip() + "，"
    return text.rstrip() + _SINGLE_PLAN_RULE.format(
        noun=noun, heading=heading, detail=detail)


