# 思考纪律注入路由：role -> 思考输出字数兜底上限（字符）。
# 不写进本表的角色 = 不注入（与 JAILBREAK_MODES「未登记默认 full」相反，此处默认不注入）。
# - 结构规划类给 30000：老板的分卷模板有【继承抄录】【情节扩展规划】【拆章决策】等
#   十来个思考大项，正常写也要上万字；上限只用来拦住「四五万字以上」那种失控。
# - 正文/改写给 20000：这两类最常出现「思考里把整章预演一遍」。
# ⚠️ 2026-11-05 老板拍板：初版 6000/3000 被判定「太少了，不合时宜」，
#   明确要求放宽到两到三万。别再按「省 token」的思路往下调。
# - check/style 是机械 JSON 审校（低温纪律优先），memory 是纯提取（破甲档都是 off），
#   注入只会挤占它们的输出预算；ai_task（build_bare）无角色、任务短，同样不注入。
THINK_GUARD_CAPS = {
    "synopsis": 30000,
    "volume": 30000,
    "volume_iter": 30000,
    "volume_chapters_iter": 30000,
    "outline": 30000,
    "detail": 30000,
    "prose": 20000,
    "prose_rewrite": 20000,
}

# 文案正文（{cap} 由 think_guard_text 替换为当前角色的上限）。
# 措辞六条红线（改动前先读）：
# ① 首段必须声明「不改内容要求/细节密度/文风」——否则模型会把纪律外溢成「正文写干」；
# ② 必须显式豁免 <draft>——否则与草稿自检协议对撞；
# ③ 必须写「以本段为准」——任务模板里「先思考输出、再正式输出」的清单先出现；
# ④ 上限必须写成「兜底 / 不是配额 / 不要求写满」——否则模型会当成目标字数写满；
# ⑤ 第三条只禁「成句的正文」，允许一句骨架（谁对谁做了什么），否则思考会僵成空话；
# ⑥ 第七条必须写「要跳就整段跳，不留空壳标题或半截思考段」——textclean 的
#    思考段剥离靠标题/锚点定位，半截段会把章标题一起吞掉（识别失败）。
_THINK_GUARD_BODY = (
    "【思考纪律（只管思考，不改任务内容；与其它任何思考要求冲突时以本段为准）】\n"
    "适用范围：模型内部思维链，以及任务模板要求的「先思考输出、再正式输出」里的思考环节。\n"
    "本段不改变任务的内容要求、细节密度和文风；草稿自检的 <draft> 块不受本段约束，"
    "仍按该协议执行。\n\n"
    "一、同一件事只推一遍。一个设定、一条判据、一处情节，推演一次、写下结论就过；\n"
    "    后文需要引用写「同上」，不换措辞复述、不回头复查、不二次确认、不推翻重来。\n"
    "二、一次定案。每个决策点只选一次；信息不足时选最合理的一种，在该条后标「默认」，\n"
    "    直接往下走，不再比较第二方案。\n"
    "三、思考里不预写正文。不写对白、不写描写、不试写成句；要举例只写一句骨架\n"
    "    （谁对谁做了什么），要判断语感只写「这里该短/该长」。\n"
    "四、内部思维链只排顺序，不预演文字。按任务模板的清单逐项推进，写成\n"
    "    「C3 情节扩展：新增 3 个环节」这样的条目名＋结论；\n"
    "    **不要在思考里写出任何一整段可以直接贴进正式输出的成稿**——\n"
    "    写「⑨ 来年：废墟空镜收束」可以，写「来年开春，草木照旧从废墟里长出来……」不行。\n"
    "    发现自己成段写正文、或成段复述上文，立刻停下，回到条目名。\n"
    "五、思考字数兜底 {cap} 字。这是防失控的上限，不是配额：常规思考应明显短于它，\n"
    "    不要求写满；写到上限立即停笔，剩下的判断留到正式输出里边写边定。\n"
    "六、思考结束直接开写。正式输出从第一个内容单元开始，开头不复述思考，\n"
    "    不写「综上」「根据以上思考」，不单独列思考摘要；结论只体现在内容里。\n"
    "七、思考输出段可以整段跳过。任务模板里的「先思考输出、再正式输出」，\n"
    "    原意是给没有内部推理能力的模型补一次「强制动脑」。\n"
    "    如果你已在内部思维链里把模板列出的思考项全部想定（继承抄录、情节扩展、\n"
    "    拆章决策等），就直接输出正式内容，跳过「思考输出」这一整段：\n"
    "    不补写形式化框架、不抄一遍结论、不写思考摘要。\n"
    "    仅当仍有未定决策时，才用不超过 500 字列出那几条，随后立刻进入正式输出。\n"
    "    要跳就整段跳，不要留下空壳标题或半截思考段；这两者都会让程序无法正确切分正文。"
)


def think_guard_text(role: str) -> str:
    """按角色返回思考纪律全文；未登记角色返回 ""（调用方跳过注入）。"""
    try:
        cap = THINK_GUARD_CAPS.get(role)
    except TypeError:
        return ""
    if not cap:
        return ""
    return _THINK_GUARD_BODY.replace("{cap}", str(cap))


def think_guard_enabled(store) -> bool:
    """协议开关（默认开）。关闭 = 不注入（任务模板里的思考环节照旧执行）。

    store 兼容两种后端（与 endmark.end_mark_enabled 同构）：
    - ProjectStore：get_setting_int 会按 GLOBAL_SETTING_KEYS 自动转发到全局库；
    - GlobalStore：直接读全局键。
    读不到/类型异常一律视为「开」——护栏默认在岗，宁可多注入一段。
    """
    try:
        return int(store.get_setting_int("think_guard_enabled", 1)) > 0
    except AttributeError:
        pass
    except (TypeError, ValueError):
        return True
    try:
        return int(store.get_global_setting("think_guard_enabled", "1")) > 0
    except Exception:
        return True
